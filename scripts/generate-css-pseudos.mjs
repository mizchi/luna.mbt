import { readFileSync, writeFileSync } from "node:fs";

// Curated selector names, not a browser-support guarantee.
// https://developer.mozilla.org/en-US/docs/Web/CSS/Reference/Selectors/Pseudo-classes
// https://developer.mozilla.org/en-US/docs/Web/CSS/Reference/Selectors/Pseudo-elements
// Keep the enum and static scanner's names/arity in one catalog.
const groups = [
  [":", false, "active any-link autofill checked default defined disabled empty enabled first-child first-of-type focus focus-visible focus-within fullscreen hover in-range indeterminate invalid last-child last-of-type link modal only-child only-of-type open optional out-of-range picture-in-picture placeholder-shown popover-open read-only read-write required root scope target user-invalid user-valid valid visited"],
  [":", true, "dir has is lang not nth-child nth-last-child nth-last-of-type nth-of-type state where"],
  ["::", false, "after backdrop before file-selector-button first-letter first-line marker placeholder selection"],
  ["::", true, "highlight part slotted"],
];
const entries = groups.flatMap(([prefix, functional, names]) => names.split(" ").map(name => ({
  variant: name.split("-").map(part => part[0].toUpperCase() + part.slice(1)).join(""),
  selector: prefix + name,
  functional,
}))).sort((a, b) => a.variant < b.variant ? -1 : a.variant > b.variant ? 1 : 0);
if (new Set(entries.map(entry => entry.variant)).size !== entries.length) throw new Error("Duplicate pseudo constructors");
const header = "// Generated by scripts/generate-css-pseudos.mjs; do not edit.\n";
const outputs = {
  "pseudo_selector.mbt": header + `
///|
/// Typed pseudo-classes and pseudo-elements. Functional arguments use CSS syntax.
/// Compound selectors and names outside this catalog can still use String.
pub(all) enum Pseudo {
${entries.map(e => `  ${e.variant}${e.functional ? "(String)" : ""}`).join("\n")}
} derive(Eq, Debug)

///|
pub fn Pseudo::css_selector(self : Pseudo) -> String {
  match self {
${entries.map(e => e.functional
  ? `    ${e.variant}(argument) => "${e.selector}(" + argument + ")"`
  : `    ${e.variant} => "${e.selector}"`).join("\n")}
  }
}
`,
  "pseudo-names.js": header + `export const pseudoNames = Object.freeze(${JSON.stringify(Object.fromEntries(entries.map(({variant, selector, functional}) => [variant, {selector, functional}])), null, 2)});\n`,
};
const root = new URL("../luna/src/x/css/", import.meta.url);
for (const [path, source] of Object.entries(outputs)) {
  const url = new URL(path, root);
  if (process.argv.includes("--check")) {
    if (readFileSync(url, "utf8") !== source) throw new Error(`${path} is stale; run just generate-css-pseudos`);
  } else {
    writeFileSync(url, source);
  }
}
console.log(`${process.argv.includes("--check") ? "Checked" : "Generated"} ${entries.length} CSS pseudo selectors`);
