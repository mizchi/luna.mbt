// Offline generation from a pinned MDN name catalog. See its source/license metadata.
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../luna/src/x/css/", import.meta.url);
const catalog = JSON.parse(readFileSync(new URL("properties.json", root), "utf8"));
const entries = catalog.properties.map(name => [
  name.split("-").map(part => part[0].toUpperCase() + part.slice(1)).join(""),
  name,
]);
if (new Set(entries.map(([variant]) => variant)).size !== entries.length) {
  throw new Error("Duplicate CSS property constructors");
}
const header = `// Generated by scripts/generate-css-properties.mjs; do not edit.\n// Names: ${catalog.source} (CC0-1.0).\n`;
const outputs = {
  "property.mbt": header + `
///|
/// CSS property names. Values still use CSS string syntax.
/// Standard and experimental unprefixed MDN names; strings remain an escape hatch.
pub(all) enum Property {
${entries.map(([variant]) => `  ${variant}`).join("\n")}
} derive(Eq, Debug)

///|
pub fn Property::css_name(self : Property) -> String {
  match self {
${entries.map(([variant, name]) => {
  const line = `    ${variant} => "${name}"`;
  return line.length > 80 ? `    ${variant} =>\n      "${name}"` : line;
}).join("\n")}
  }
}
`,
  "property-names.js": header + `export const propertyNames = Object.freeze(${JSON.stringify(Object.fromEntries(entries), null, 2)});\n`,
};
for (const [path, source] of Object.entries(outputs)) {
  const url = new URL(path, root);
  if (process.argv.includes("--check")) {
    if (readFileSync(url, "utf8") !== source) throw new Error(`${path} is stale; run just generate-css-properties`);
  } else {
    writeFileSync(url, source);
  }
}
console.log(`${process.argv.includes("--check") ? "Checked" : "Generated"} ${entries.length} CSS properties`);
